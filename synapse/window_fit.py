"""Вписать окно в экран — общее правило для ОБЕИХ панелей (Qt и запасной Tk).

Зачем (v0.20.1, слово Стаса 26.09.2026: «ты ерунду какую-то сделала - теперь у меня
окно в экран не влазит. при том что FullHD - сделай нормально универсально под любой
экран»).

ПРИЧИНА, замером, а не на глаз: окно требовало минимум **2246x765** пикселей при
FullHD 1920. Виновата не «сложная графика», а ЗАКОН Qt: у QLabel БЕЗ переноса слов
`minimumSizeHint()` равен ширине ВСЕГО текста. Подпись тела («задето 302 из 302 ·
связей 3004 · энергия 0.0003 · импульс 0.0 · режим off») просила 1488 px, строка
ответа — 960 px; вместе с полотном тела (430) выходило 2246 px, то есть окно физически
не могло стать уже, чем экран.

Лечится это в двух местах, и оба здесь видны числом:
  1) `clamp_size()` — окно НИКОГДА не больше доступного места экрана;
  2) подписи (FixedLine в qt_panel.py) просят мало ширины, а лишнее режут многоточием.
Помощник отдельный и чистый (без Qt и без Tk), поэтому обе панели берут его, и его
можно проверить тестом, не поднимая настоящее окно.
"""
from __future__ import annotations

#: Ниже этого окно не имеет смысла: интерфейс станет нечитаемым.
MIN_W, MIN_H = 480, 360

#: Запас от края экрана: заголовок окна и панель задач не должны съедать место.
MARGIN_W, MARGIN_H = 40, 60


def clamp_size(w: int, h: int, avail_w: int, avail_h: int,
               margin_w: int = MARGIN_W, margin_h: int = MARGIN_H) -> tuple[int, int]:
    """Желаемый размер -> размер, который ВЛЕЗАЕТ в доступную площадь.

    Доступная площадь — не размер экрана, а `availableGeometry()`, то есть за вычетом
    панели задач. Меньше MIN_W/MIN_H не отдаём: если экран совсем крошечный, честнее
    окно, торчащее за край, чем столбик шириной в палец.
    """
    fit_w = max(MIN_W, int(avail_w) - int(margin_w))
    fit_h = max(MIN_H, int(avail_h) - int(margin_h))
    return (max(MIN_W, min(int(w), fit_w)), max(MIN_H, min(int(h), fit_h)))
