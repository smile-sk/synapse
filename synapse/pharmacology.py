"""Фармакология тела Synapse — знак синапса, а не только цвет узла.

СЛОВО СТАСА 25.09.2026: «конечно делай все по настоящему, мы же не для декораций
делаем». До этого модуля нейромедиатор влиял ТОЛЬКО на краску: волна шла по весам
связей, и тормозной нейрон вёл себя как возбуждающий. У настоящего червя это не
так, и вот что об этом известно (единственный источник — свойство самого
трансмиттера; ничего не выдумываем на ходу):

  * GABA — единственный надёжно ТОРМОЗНОЙ быстрый медиатор у C. elegans. В нашем
    теле его несут 26 нейронов: DD1..DD6 и VD1..VD13 (тормозят дорсальную и
    вентральную мускулатуру тела), RMED/RMEL/RMER/RMEV (мышцы головы), AVL и DVB
    (кишечная мускулатура), RIS (нейрон сна). Торможение — гиперполяризация цели,
    то есть ВЫЧИТАНИЕ из её возбуждения, а не «слабое возбуждение».
  * Ацетилхолин — основной возбуждающий: моторные нейроны → мышцы (129 узлов).
  * Глутамат: в сети НЕЙРОН-НЕЙРОН червя возбуждает (сенсорные → вставочные,
    71 узел в нашем теле). У нервно-мышечного соединения он, наоборот, тормозит
    через хлорные каналы GluCl (та самая мишень ивермектина) — но МЫШЦ В НАШЕМ
    ГРАФЕ НЕТ, поэтому в нашем теле он возбуждающий. Это переключается настройкой
    body.nt.glutamate_inhibitory, а не спором в комментарии.
  * Моноамины (дофамин, серотонин, октопамин; тирамин в теле отсутствует) — НЕ
    быстрый синапс: они выделяются в объём и меняют ВОЗБУДИМОСТЬ контура на
    секунды. Поэтому они не проводят быстрый ток по своей связи, а «подкручивают
    тонус» своих целей:
        серотонин  + (бодрость, движение; замедление на пище)
        октопамин  + (тревога/расселение — «драться или бежать» у беспозвоночных)
        дофамин    − (базовое замедление при пище: тормозит движение)
        тирамин    − (антагонист октопамина)
  * У 59 узлов медиатор в атласе НЕ назван. Они получают нейтральный знак
    возбуждения и честно рисуются серым: физиологию им выдумывать я не буду.

ГРАНИЦЫ ЧЕСТНОСТИ. Мы знаем медиатор нейрона и его связи — этого достаточно для
знака передачи. Чего мы НЕ знаем: сила отдельного синапса по типу (у нас вес —
число связей из Cook2019), поэтому тормозной «вес» равен возбуждающему, а
регулируется одним множителем inhibitory_gain. Поведение, а не анатомия: знак —
свойство ПРЕСИНАПТИЧЕСКОГО нейрона, поэтому вся исходящая связь GABA-узла
тормозит целиком.
"""
from __future__ import annotations

# Типы передачи: быстрая передача (exc/inh) и объёмная модуляция (mod).
EXC = "exc"
INH = "inh"
MOD = "mod"

# Кто известен как тормозной. Список закрытый: добавить сюда медиатор можно
# только с обоснованием, иначе знак поедет втихую.
INHIBITORY = ("GABA",)

# Моноамины: объёмная передача. Знак — направление тонуса (не ток по связи).
MODULATORS: dict[str, float] = {
    "Serotonin": +1.0,
    "Octopamine": +1.0,
    "Dopamine": -1.0,
    "Tyramine": -1.0,
}

# Возбуждающие быстрые медиаторы. Пустая строка — «атлас молчит»: нейтральный
# знак возбуждения, потому что неизвестность не повод придумывать торможение.
EXCITATORY = ("Acetylcholine", "Glutamate", "")

# Ключи словаря для карточки узла и легенды (техническое слово остаётся кодом,
# переводится только подпись).
KIND_KEYS = {EXC: "nt.kind.exc", INH: "nt.kind.inh", MOD: "nt.kind.mod", "unknown": "nt.kind.unknown"}


def is_modulator(nt: str) -> bool:
    return str(nt or "") in MODULATORS


def kind(nt: str, glutamate_inhibitory: bool = False) -> str:
    """Тип передачи: exc | inh | mod. Чистая функция — её и проверяет тест."""
    n = str(nt or "")
    if n in MODULATORS:
        return MOD
    if n in INHIBITORY:
        return INH
    if n == "Glutamate" and glutamate_inhibitory:
        return INH
    return EXC


def sign(nt: str, glutamate_inhibitory: bool = False) -> float:
    """Знак БЫСТРОЙ передачи: +1 возбуждает, −1 тормозит, 0 не проводит ток."""
    k = kind(nt, glutamate_inhibitory=glutamate_inhibitory)
    if k == MOD:
        return 0.0
    return -1.0 if k == INH else 1.0


def tone_sign(nt: str) -> float:
    """Направление тонуса для модулятора (0 для быстрых медиаторов)."""
    return float(MODULATORS.get(str(nt or ""), 0.0))


def kind_key(nt: str, glutamate_inhibitory: bool = False) -> str:
    return KIND_KEYS.get(kind(nt, glutamate_inhibitory=glutamate_inhibitory), "nt.kind.unknown")


def known(nt: str) -> bool:
    """Есть ли у медиатора закон в этом модуле (для честной пометки «неизвестно»)."""
    n = str(nt or "")
    return bool(n) and (n in INHIBITORY or n in MODULATORS or n in EXCITATORY)


def summary(nts) -> dict:
    """Сколько узлов каждого типа передачи — для легенды и отчёта."""
    out = {EXC: 0, INH: 0, MOD: 0}
    for nt in nts:
        out[kind(nt)] = out.get(kind(nt), 0) + 1
    return out
