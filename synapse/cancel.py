"""Снятие миссии «на ходу» — то, что делает кнопку «Удалить» правдой.

Зачем (слово Стаса 26.09.2026: «останавливать и удалять нужно — если на кнопке
написано УДАЛИТЬ!… оно просто пишет running уже 5 минут»).

Прежнее поведение: у идущей миссии ставился статус refused, а РАБОТА ШЛА ДАЛЬШЕ —
аудит сети с полным диапазоном портов молотил ещё минуты, и оператор видел вечное
«running». Причина не в панели: инструмент — обычная синхронная функция внутри
такта, и остановить её снаружи было нечем.

Здесь для этого одно место и один флаг на миссию: инструмент спрашивает
`requested(id)` в своих циклах (хосты, куски портов, перед запуском метода) и
прекращает работу. Флаг снимается, когда миссия завершилась (`agent._finish`),
иначе следующая миссия с тем же id остановилась бы «сама».

Модуль нарочно без зависимостей: его зовут и агент, и инструменты, и панель.
"""
from __future__ import annotations

import threading
import time

_LOCK = threading.Lock()
_MARKED: dict[str, float] = {}


def request(mid: str) -> bool:
    """Попросить миссию остановиться. True — просьба записана сейчас."""
    mid = str(mid or "")
    if not mid:
        return False
    with _LOCK:
        _MARKED[mid] = time.monotonic()
    return True


def requested(mid: str) -> bool:
    """Просили ли остановить эту миссию."""
    with _LOCK:
        return str(mid or "") in _MARKED


def clear(mid: str) -> None:
    """Миссия закончилась — снять просьбу (иначе она сработает в следующий раз)."""
    with _LOCK:
        _MARKED.pop(str(mid or ""), None)


def asked() -> list[str]:
    """Кого сейчас просят остановиться (для журнала и тестов)."""
    with _LOCK:
        return sorted(_MARKED)
