def _deep_merge(base: dict, over: dict) -> dict:
    """Память главнее умолчания; списки — ЦЕЛИКОМ из памяти, не поэлементно."""
    out = dict(base)
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def drop_retired(cfg: dict) -> tuple[dict, list[str]]:
    """Убрать выведенные ключи. Возвращает (чистый конфиг, что убрано)."""
    dropped: list[str] = []
    for section, keys in RETIRED_KEYS.items():
        if section == ROOT_SECTION:               # ключи верхнего уровня
            for k in keys:
                if k in cfg:
                    cfg.pop(k, None)
                    dropped.append(k)
            continue
        block = cfg.get(section)
        if isinstance(block, dict):
            for k in keys:
                if k in block:
                    block.pop(k, None)
                    dropped.append(f"{section}.{k}")
    return cfg, dropped


def _migrate_brain_args(cfg: dict) -> dict:
    """Старые -ngl/-c из server_args переносим в свои ключи (v0.20.0).

    Нужно, чтобы у оператора НЕ поменялось поведение при обновлении: в его
    config.json лежало server_args ["-ngl","10","-c","4096"], и эти же числа
    должны оказаться в ngl/ctx. Идемпотентно: после первого сохранения в
    server_args этих ключей уже нет, и функция ничего не делает.
    """
    brain = cfg.get("brain")
    if not isinstance(brain, dict):
        return cfg
    args = [str(a) for a in (brain.get("server_args") or [])]
    rest: list[str] = []
    i = 0
    while i < len(args):
        a = args[i]
        if a in ("-ngl", "--n-gpu-layers", "-c", "--ctx-size") and i + 1 < len(args):
            try:
                val = int(float(args[i + 1]))
            except ValueError:
                rest.extend([a, args[i + 1]])
                i += 2
                continue
            brain["ngl" if a in ("-ngl", "--n-gpu-layers") else "ctx"] = val
            i += 2
            continue
        rest.append(a)
        i += 1
    brain["server_args"] = rest
    return cfg


def load(path: Path | None = None) -> dict:
    p = Path(path) if path else CONFIG_PATH
    disk = {}
    if p.exists():
        try:
            disk = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            disk = {}
    merged = _deep_merge(DEFAULTS, disk if isinstance(disk, dict) else {})
    merged = _migrate_brain_args(merged)
    merged, _ = drop_retired(merged)
    return merged


_CACHE: dict[str, tuple] = {}


def cached(path: Path | None = None) -> dict:
    """load(), но с памятью по отпечатку файла.

    Зачем: такт тела идёт 20 раз в секунду, и каждый step() читал config.json
    с диска и разбирал его заново (замер: 0.6 мс на кадр — это чистые потери).
    Отпечаток = (mtime, размер), поэтому правка настроек видна СРАЗУ, а не по таймеру.

    Возвращённый словарь — общий: его НЕЛЬЗЯ менять на месте (правки делай через
    load() + save()).
    """
    p = Path(path) if path else CONFIG_PATH
    try:
        st = p.stat()
        key = (st.st_mtime_ns, st.st_size)
    except OSError:
        key = (0, 0)
    hit = _CACHE.get(str(p))
    if hit is not None and hit[0] == key:
        return hit[1]
    cfg = load(p)
    _CACHE[str(p)] = (key, cfg)
    return cfg


def forget_cache() -> None:
    """Забыть память настроек (тестам и смене файла на ходу)."""
    _CACHE.clear()


def save(cfg: dict, path: Path | None = None) -> Path:
    p = Path(path) if path else CONFIG_PATH
    p.parent.mkdir(parents=True, exist_ok=True)
    clean, _ = drop_retired(dict(cfg))
    tmp = p.with_suffix(p.suffix + ".tmp")
    tmp.write_text(json.dumps(clean, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(tmp, p)          # читатель не застанет половину файла
    return p


def ensure_files(path: Path | None = None) -> Path:
    """Первый запуск: создаём config.json из умолчаний, если его нет."""
    p = Path(path) if path else CONFIG_PATH
    if not p.exists():
        save(DEFAULTS, p)
    return p
